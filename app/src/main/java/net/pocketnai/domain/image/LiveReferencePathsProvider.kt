package net.pocketnai.domain.image

/**
 * "数据库之外还需要保留的参考图文件"。
 *
 * 参考图是内容寻址的，启动清理按"仍被引用的路径集合"回收文件。数据库里的
 * `reference_images` 只覆盖**已经提交过**的生成；而用户刚选好图、还没点生成时，
 * 那几张图只存在于编辑区草稿里，没有任何数据库记录。
 *
 * 少了这一层，用户选图后重启应用（或手动点"清理孤立临时文件"），
 * 图片会被当成孤儿删掉，界面随即报"参考图已不在本机" —— 真机验证时抓到的缺陷。
 *
 * 抽成接口而不是让仓库直接读草稿：[GenerationRepository] 不该知道"编辑区草稿"这种界面概念，
 * 它只需要一份"这些路径别删"的集合。
 */
fun interface LiveReferencePathsProvider {

    /** 当前仍然需要保留的参考图相对路径。 */
    fun provide(): Set<String>
}
